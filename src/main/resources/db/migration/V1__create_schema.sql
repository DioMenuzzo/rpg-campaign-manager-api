-- Etapa 1: modelo relacional de campanhas, personagens, NPCs e sessões.
-- Fichas de personagem completas (específicas de cada sistema) ficam no MongoDB na etapa 2.

CREATE TABLE campaigns (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL,
    game_system  VARCHAR(30)  NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    game_master  VARCHAR(80),
    description  TEXT,
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_campaigns_game_system CHECK (game_system IN ('DND_5E', 'ORDEM_PARANORMAL', 'OTHER')),
    CONSTRAINT ck_campaigns_status      CHECK (status IN ('PLANNING', 'ACTIVE', 'ON_HOLD', 'FINISHED'))
);

CREATE TABLE player_characters (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id      BIGINT       NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    name             VARCHAR(120) NOT NULL,
    player_name      VARCHAR(80),
    character_class  VARCHAR(60),
    level            INTEGER,
    status           VARCHAR(20)  NOT NULL,
    backstory        TEXT,
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_player_characters_status CHECK (status IN ('ALIVE', 'DEAD', 'MISSING', 'RETIRED')),
    CONSTRAINT ck_player_characters_level  CHECK (level IS NULL OR level BETWEEN 0 AND 100)
);
CREATE INDEX ix_player_characters_campaign ON player_characters (campaign_id);

CREATE TABLE npcs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id   BIGINT       NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    name          VARCHAR(120) NOT NULL,
    role          VARCHAR(120),
    location      VARCHAR(120),
    attitude      VARCHAR(20)  NOT NULL,
    alive         BOOLEAN      NOT NULL DEFAULT TRUE,
    description   TEXT,
    secret_notes  TEXT,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_npcs_attitude CHECK (attitude IN ('ALLY', 'NEUTRAL', 'HOSTILE', 'UNKNOWN'))
);
CREATE INDEX ix_npcs_campaign ON npcs (campaign_id);

CREATE TABLE game_sessions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id     BIGINT       NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    session_number  INTEGER      NOT NULL,
    title           VARCHAR(150),
    scheduled_at    TIMESTAMPTZ,
    status          VARCHAR(20)  NOT NULL,
    summary         TEXT,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_game_sessions_campaign_number UNIQUE (campaign_id, session_number),
    CONSTRAINT ck_game_sessions_status CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_game_sessions_number CHECK (session_number > 0)
);
-- Consulta típica da etapa 4: "próximas sessões agendadas"
CREATE INDEX ix_game_sessions_status_scheduled ON game_sessions (status, scheduled_at);
